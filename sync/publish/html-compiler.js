/**
 * Render navigation tree to HTML list.
 */
function renderNavHTML(navTree, currentSlug, theme) {
    if (!navTree || navTree.length === 0) return '';

    const renderItems = (items) => {
        return items.map(item => {
            const isActive = item.slug === currentSlug;
            const activeClass = isActive ? ' active' : '';
            const children = item.children && item.children.length > 0
                ? `\n<ul>${renderItems(item.children)}</ul>\n`
                : '';
            return `<li><a href="/${item.slug}.html" class="${activeClass}">${escapeHTML(item.title)}</a>${children}</li>`;
        }).join('\n');
    };

    return `<ul>\n${renderItems(navTree)}\n</ul>`;
}

/**
 * Render layout regions to HTML.
 */
function renderBodyHTML(regions, theme) {
    const html = [];

    // Group sidebar regions separately
    const sidebars = regions.filter(r => r.region === 'sidebar');
    const mainRegions = regions.filter(r => r.region !== 'sidebar');

    for (const region of mainRegions) {
        const cssClass = `region-${region.region}`;
        const contentHTML = asciiToHTMLSpans(region.resolvedContent);

        if (region.region === 'header') {
            html.push(`<div class="${cssClass}">`);
            html.push(`<h1>${escapeHTML(extractTitle(region.resolvedContent))}</h1>`);
            html.push(`<div class="ascii-content">${contentHTML}</div>`);
            html.push(`</div>`);
        } else if (region.region === 'footer') {
            html.push(`<div class="${cssClass}">`);
            html.push(`<div class="ascii-content">${contentHTML}</div>`);
            html.push(`</div>`);
        } else {
            html.push(`<div class="${cssClass}">`);
            html.push(`<div class="ascii-content">${contentHTML}</div>`);
            html.push(`</div>`);
        }
    }

    for (const sb of sidebars) {
        const contentHTML = asciiToHTMLSpans(sb.resolvedContent);
        html.push(`<div class="region-sidebar">`);
        html.push(`<div class="ascii-content">${contentHTML}</div>`);
        html.push(`</div>`);
    }

    return html.join('\n');
}

/**
 * Convert raw ASCII content to HTML spans.
 * Each line becomes a <span class="line">.
 */
function asciiToHTMLSpans(content) {
    if (!content) return '';
    return content
        .split('\n')
        .map(line => `<span class="line">${escapeHTML(line)}</span>`)
        .join('\n');
}

/**
 * Extract a title from content (first non-empty line).
 */
function extractTitle(content) {
    if (!content) return 'Untitled';
    const lines = content.split('\n');
    for (const line of lines) {
        const trimmed = line.trim();
        if (trimmed) return trimmed.slice(0, 60);
    }
    return 'Untitled';
}

/**
 * Convert [r,g,b,a] array to CSS rgba() string.
 */
function rgbaToCSS(rgba) {
    if (!Array.isArray(rgba) || rgba.length < 3) return 'rgba(0,0,0,1)';
    const [r, g, b, a = 255] = rgba;
    return `rgba(${r},${g},${b},${(a / 255).toFixed(2)})`;
}

/**
 * Escape HTML special characters.
 */
function escapeHTML(str) {
    if (!str) return '';
    return str
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}
